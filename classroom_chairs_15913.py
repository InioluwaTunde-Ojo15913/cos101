#1. Counting number of chairs in the classroom
#2. Input- Number of rows, number of chairs in each row
#   Process- Number of rows * number of chairs in each row
#   Output- Total number of chairs in the class
#3. Start
#       Get number of rows,
#       Get number of chairs per row,
#       Print number of rows,
#       Print number of chairs per row,
#       Multiply number of rows by number of chairs per row to get total number of chairs,
#       Print total number of chairs
#   Stop
#4. START
#       SET rows TO 6
#       SET number_per_row TO 8
#       DISPLAY rows
#       DISPLAY number_per_row
#       CALCULATE total_number_of_chairs AS rows x number_per_row
#       DISPLAY total_number_of_chairs
#   STOP

rows = 6
number_per_row = 8
print("Number of rows: ", rows)
print("Number of chairs per row: ", number_per_row)
total_number_of_chairs = rows * number_per_row
print("Total number of chairs: ", total_number_of_chairs)

